def build_star(raw):
    seq = raw["seq"]
    perm = raw["perm"]
    chunks = [seq[i] for i in perm]
    correct_order = [chunks.index(seq[i]) + 1 for i in range(4)]
    star_chunk_num = correct_order[2] # slot index 2 is the 3rd slot
    arrow = " ➔ ".join([f"{chunks[num-1]} ({num})" for num in correct_order])
    explanation = f"{arrow}。★ 為 {star_chunk_num} 號。{raw['note']}"
    return {
        "id": raw["id"],
        "preText": raw["pre"],
        "postText": raw["post"],
        "starIndex": 2,
        "chunks": chunks,
        "correctOrder": correct_order,
        "explanation": explanation,
        "fullSentence": raw["full"],
        "translation": raw["trans"]
    }

