def generate_passage_quizzes():
    quizzes = []
    assert len(RAW_PASSAGES) == 10, f"Expected 10 passages, got {len(RAW_PASSAGES)}"
    total_q_count = 0
    answer_dist = {}
    
    for p in RAW_PASSAGES:
        assert "【 01 】" in p["passage"]
        assert "【 02 】" in p["passage"]
        assert "【 03 】" in p["passage"]
        assert len(p["questions"]) == 3
        
        q_items = []
        for q in p["questions"]:
            target_idx = q["target_idx"]
            opts = [None] * 4
            opts[target_idx - 1] = q["ans"]
            d_idx = 0
            for j in range(4):
                if opts[j] is None:
                    opts[j] = q["distractors"][d_idx]
                    d_idx += 1
            
            q_items.append({
                "blankNumber": q["blankNumber"],
                "options": opts,
                "correctIndex": target_idx,
                "explanation": q["exp"]
            })
            total_q_count += 1
            answer_dist[target_idx] = answer_dist.get(target_idx, 0) + 1
            
        quizzes.append({
            "id": p["id"],
            "title": p["title"],
            "genre": p["genre"],
            "passage": p["passage"],
            "questions": q_items,
            "translation": p["translation"]
        })
        
    return quizzes, answer_dist

