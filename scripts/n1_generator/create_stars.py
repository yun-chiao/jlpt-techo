# Permutations where P[2] (0-indexed 2, i.e. 3rd slot) is a specific target number:
# target_star in 1..4:
PERMS = {
    1: [2, 3, 1, 4], # chunks[1]=p1, chunks[2]=p2, chunks[0]=p3, chunks[3]=p4 -> star is chunk 1
    2: [3, 4, 2, 1], # chunks[2]=p1, chunks[3]=p2, chunks[1]=p3, chunks[0]=p4 -> star is chunk 2
    3: [1, 2, 3, 4], # chunks[0]=p1, chunks[1]=p2, chunks[2]=p3, chunks[3]=p4 -> star is chunk 3
    4: [2, 1, 4, 3], # chunks[1]=p1, chunks[0]=p2, chunks[3]=p3, chunks[2]=p4 -> star is chunk 4
}

def generate_star_quizzes():
    quizzes = []
    assert len(RAW_STARS) == 50, f"Expected 50 items, got {len(RAW_STARS)}"
    for i, s in enumerate(RAW_STARS):
        target_star = (i % 4) + 1  # 1, 2, 3, 4 balanced (13, 13, 12, 12)
        perm = PERMS[target_star]
        assert perm[2] == target_star
        p = s["pieces"]
        assert len(p) == 4
        
        # perm tells us which chunk number (1-based) is placed at each slot
        # slot 0 has chunk perm[0] -> so chunks[perm[0] - 1] = p[0]
        # slot 1 has chunk perm[1] -> so chunks[perm[1] - 1] = p[1]
        # slot 2 has chunk perm[2] -> so chunks[perm[2] - 1] = p[2]
        # slot 3 has chunk perm[3] -> so chunks[perm[3] - 1] = p[3]
        chunks = [None] * 4
        for slot in range(4):
            chunks[perm[slot] - 1] = p[slot]
        
        # Verify reconstruction
        reconstructed = (s["pre"].strip() + "".join(chunks[perm[slot]-1] for slot in range(4)) + s["post"].strip()).replace(" ", "").replace("　", "")
        expected = s["full"].replace(" ", "").replace("　", "")
        assert reconstructed == expected, f"Item {i+1} mismatch:\nGot:  {reconstructed}\nWant: {expected}"
        
        star_num = perm[2]
        star_chunk = chunks[star_num - 1]
        
        # Build explanation
        step_arrows = f"{p[0]} ({perm[0]}) ➔ {p[1]} ({perm[1]}) ➔ {p[2]} ({perm[2]}) ➔ {p[3]} ({perm[3]})。★ 為 {star_num} 號【{star_chunk}】。{s['note']}"
        
        quizzes.append({
            "id": f"n1-star-{i+1}",
            "preText": s["pre"],
            "postText": s["post"],
            "starIndex": 2,
            "chunks": chunks,
            "correctOrder": perm,
            "explanation": step_arrows,
            "fullSentence": s["full"],
            "translation": s["trans"]
        })
    return quizzes

if __name__ == "__main__":
    qs = generate_star_quizzes()
    print(f"Successfully verified and generated {len(qs)} star scramble quizzes.")
    counts = {}
    for q in qs:
        star_choice = q["correctOrder"][q["starIndex"]]
        counts[star_choice] = counts.get(star_choice, 0) + 1
    print("Star choice distribution:", counts)
