def generate_sentence_quizzes():
    quizzes = []
    assert len(RAW_SENTENCES) == 120, f"Expected 120 items, got {len(RAW_SENTENCES)}"
    for i, q in enumerate(RAW_SENTENCES):
        correct_idx = (i % 4) + 1  # Exactly 30 of each 1, 2, 3, 4
        opts = [None] * 4
        opts[correct_idx - 1] = q["ans"]
        d_idx = 0
        for j in range(4):
            if opts[j] is None:
                opts[j] = q["distractors"][d_idx]
                d_idx += 1
        quizzes.append({
            "id": f"n1-s-{i+1}",
            "question": q["q"],
            "options": opts,
            "correctIndex": correct_idx,
            "explanation": q["exp"],
            "targetGrammar": q["grammar"]
        })
    return quizzes

