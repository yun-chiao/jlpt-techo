    qs = generate_sentence_quizzes()
    print(f"Generated {len(qs)} sentence quizzes.")
    counts = {}
    for q in qs:
        c = q["correctIndex"]
        counts[c] = counts.get(c, 0) + 1
    print("CorrectIndex distribution:", counts)
