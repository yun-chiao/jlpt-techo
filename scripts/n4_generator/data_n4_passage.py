def get_passage_quizzes():
    passages = []
    global_q_index = 0
    for p in RAW_PASSAGES:
        qs = []
        for q in p["questions"]:
            target_idx = (global_q_index % 4) + 1  # 1, 2, 3, 4 balanced
            global_q_index += 1
            
            opts = list(q["distractors"])
            opts.insert(target_idx - 1, q["correct"])
            
            qs.append({
                "blankNumber": q["blankNumber"],
                "options": opts,
                "correctIndex": target_idx,
                "explanation": q["explanation"]
            })
            
        passages.append({
            "id": p["id"],
            "title": p["title"],
            "genre": p["genre"],
            "passage": p["passage"],
            "questions": qs,
            "translation": p["translation"]
        })
    return passages

